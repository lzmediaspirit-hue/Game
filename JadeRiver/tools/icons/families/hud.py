"""HUD glyphs: 16x16 art px (32x32 screen), pale-gold glyph with ink outline.

Each glyph is ASCII art (max 14x14 so the outline fits):
  '#' glyph fill (auto bevel: lit top-left edge, warm-gold bottom-right edge)
  '+' warm-gold detail    'o' ink detail (engraved line / pupil)
  '*' bright highlight    '.' / ' ' empty
Glyphs are centred on the canvas by their bounding box.
"""
import math

import numpy as np

from pix import Canvas, Ramp
from registry import register

FAM, GROUP = 'hud', 'hud'
GOLD = Ramp(['#9A6A35', '#E5B84C', '#FFE6A1', '#FFF6D6'], '#071015')
INK = '#071015'


def glyph_canvas(rows, dx=0, dy=0):
    c = Canvas(16)
    h = len(rows)
    w = max(len(r) for r in rows)
    ox = (16 - w) // 2 + dx
    oy = (16 - h) // 2 + dy
    fill = c.from_rows(rows, ox, oy, chars='#+o*')
    c.put(fill, GOLD, 'bevel', base=2)
    c.put(c.from_rows(rows, ox, oy, chars='+'), GOLD[1], 'flat', out=INK)
    c.put(c.from_rows(rows, ox, oy, chars='*'), GOLD[3], 'flat', out=INK)
    c.put(c.from_rows(rows, ox, oy, chars='o'), INK, 'flat', out=INK)
    c.outline(col=INK)
    return c


