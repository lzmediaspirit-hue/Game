def taiji():
    c = Canvas(16)
    cx, cy, r = 8.0, 8.0, 6.6
    X, Y = c.X, c.Y
    disc = (X - cx) ** 2 + (Y - cy) ** 2 <= r * r
    top = (X - cx) ** 2 + (Y - (cy - r / 2)) ** 2 <= (r / 2) ** 2
    bot = (X - cx) ** 2 + (Y - (cy + r / 2)) ** 2 <= (r / 2) ** 2
    yang = disc & (((X < cx) & ~bot) | top)
    yin = disc & ~yang
    c.put(disc, GOLD, 'bevel', base=2)
    c.put(yin, INK, 'flat', out=INK)
    c.put(disc & ~erode_ring(c, disc), GOLD, 'flat', base=2)
    c.put(c.circle(cx, cy - r / 2, 1.2), INK, 'flat', out=INK)
    c.put(c.circle(cx, cy + r / 2, 1.2), GOLD, 'flat', base=2)
    c.outline(col=INK)
    return c


def erode_ring(c, m):
    from pix import erode4
    return erode4(m)


